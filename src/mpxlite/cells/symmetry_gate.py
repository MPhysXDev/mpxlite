@dataclass
class _Kind:
    dim: int
    conn: np.ndarray  # (m, k) node rows
    phys: np.ndarray  # (m,) physical tag
    number: np.ndarray  # (m,) element number


@dataclass
class _GateMesh:
    path: Path
    numbers: np.ndarray
    xyz: np.ndarray
    kinds: list[_Kind] = field(default_factory=list)


def _read(path: Path) -> _GateMesh:
    text = path.read_text(encoding="utf-8")
    lines = text.splitlines()
    sections = _sections(lines)
    version, major = _read_format(path, lines, sections)
    if major != 2:
        raise _msh2_only(path, "the symmetry gate reads", version)
    i = sections["Nodes"]
    n = int(lines[i])
    arr = np.array(" ".join(lines[i + 1 : i + 1 + n]).split(), dtype=float).reshape(n, 4)
    numbers = arr[:, 0].astype(np.int64)
    row = np.full(int(numbers.max()) + 1, -1, dtype=np.int64)
    row[numbers] = np.arange(n)
    links = _read_links(lines, sections.get("Periodic"), v41=False)
    bloch = {e for lk in links if lk.dim == 2 for e in (lk.slave, lk.master)}
    j = sections["Elements"]
    rows: dict[int, list[list[int]]] = {t: [] for t in _CHECKED}
    for line in lines[j + 1 : j + 1 + int(lines[j])]:
        t = line.split()
        etype, ntags = int(t[1]), int(t[2])
        if etype not in _CHECKED:
            if etype in _IGNORED:
                continue
            raise UnsupportedMeshFormatError(
                f"{path}: element type {etype} (linear tetrahedra and triangles only)"
            )
        phys = int(t[3]) if ntags >= 1 else 0
        ent = int(t[4]) if ntags >= 2 else 0
        if etype == 2 and ent in bloch:
            continue
        rows[etype].append([int(t[0]), phys, *(int(v) for v in t[3 + ntags :])])
    mesh = _GateMesh(path, numbers, np.ascontiguousarray(arr[:, 1:4]))
    for etype, (nn, dim) in _CHECKED.items():
        a = np.array(rows[etype], dtype=np.int64).reshape(-1, 2 + nn)
        mesh.kinds.append(_Kind(dim, row[a[:, 2:]], a[:, 1], a[:, 0]))
    return mesh


