MATCH_TOL = 1e-9
"""Node match tolerance, relative to the lattice scale ``max |T_ij|`` (round-off)."""

_SHIFTS = np.array([(a, b) for a in (0, -1, 1) for b in (0, -1, 1)], dtype=np.int64)
"""Lattice shifts tried (zero first) to find a periodic copy."""

_CHECKED = {4: (4, 3), 2: (3, 2)}
"""MSH element type -> (nodes, dimension) of the checked kinds (tetrahedron, triangle)."""

_IGNORED = {1, 15}
"""Element types skipped (lines, points)."""

_MAX_PROBE = 256
"""Largest number of unmatched node images whose nearest node is searched (worst mismatch)."""


class MeshSymmetryError(SymmetricNumberingError):
    """The mesh does not have the declared symmetry (see :class:`MeshSymmetryReport`)."""

    def __init__(self, message: str, report: MeshSymmetryReport | None = None) -> None:
        super().__init__(message)
        self.report = report


class SymmetryGateSkipped(UserWarning):
    """A declared symmetry is used without the mesh check (explicit opt-out)."""


def warn_gate_skipped(where: str, *, stacklevel: int = 3) -> None:
    """Emit the :class:`SymmetryGateSkipped` warning of an opt-out at ``where``."""
    warnings.warn(
        f"{where}: the declared symmetry is used WITHOUT checking the mesh (opt-out); "
        "results are exact only if the mesh, its tags and its node numbering are invariant "
        "(mpxlite.cells.symmetry_gate)",
        SymmetryGateSkipped,
        stacklevel=stacklevel,
    )


