r"""Symmetry gate: verify that a mesh has the symmetry a case declares.

A case only *declares* its symmetry (a point group about a centre,
:class:`~mpxlite.cells.spacegroup.LatticeOp` objects); every exact use of
it -- the folding of a Bloch set by a macrocell, a symmetry map of the
unknowns, a symmetry of a reduced model -- silently returns wrong data on a
mesh that does not have it. :func:`require_mesh_symmetry` is the check to
run before each of these uses; it raises
:class:`MeshSymmetryError` unless, for every declared operation
:math:`\mathcal G` (modulo the lattice),

* **nodes**: the image of every node is a node (coordinates, to
  :data:`MATCH_TOL` of the lattice scale, i.e. round-off);
* **elements**: the image of every tetrahedron and every triangle is an
  element of the mesh (translated by a lattice vector into the window);
  the triangles of the 2-D ``$Periodic`` (Bloch) surfaces are excluded, as
  in :func:`~mpxlite.cells.spacegroup.check_symmetric_numbering`: their
  nodes and the tetrahedra on them are checked, their tags are those of
  the periodic faces;
* **tags**: the image of an element of physical tag ``a`` carries the
  declared image tag of ``a`` (the tags exchanged by the operation, a
  region permutation); every undeclared tag is fixed;
* **numbering**: the node numbers of every image element are in the same
  order as those of the element, so the second-order space is invariant
  (GetDP orients edges and keeps two of the three facet functions of a
  triangle by node number; see :mod:`mpxlite.cells.spacegroup`);

and, for the group generated by the operations, **no element holds two
nodes of one orbit** (then no numbering preserves the order: an asymmetric
unit bounded by edges / faces identified by a rotation or a glide, e.g. a
C4 quadrant).

Opting out (``check=False`` at the call sites) is possible for a study of
the discretisation error of a declared-but-approximate symmetry; it emits
a :class:`SymmetryGateSkipped` warning every time.

The check is vectorised (sorted integer keys of the quantised coordinates
and of the element rows; no Python loop over nodes or elements): a few
tenths of a second for the 8 operations of C4v on the 121k-DOF
second-order cell of 121k unknowns (20k elements). Linear tetrahedra and
triangles of an MSH 2.x ASCII mesh only; point and line
elements are not checked.
"""

