class _RowIndex:
    """Exact lookup of integer rows: ``find(q)`` -> row number or ``-1``.

    The rows are encoded column by column into dense ranks (``rank * span +
    value``, re-ranked after each column), so every operation is a 1-D
    ``int64`` sort / ``searchsorted``.
    """

    def __init__(self, rows: np.ndarray) -> None:
        rows = np.asarray(rows, dtype=np.int64)
        self._lo = rows.min(axis=0) if len(rows) else np.zeros(rows.shape[1], np.int64)
        self._levels: list[np.ndarray] = []
        self._spans: list[int] = []
        rank = np.zeros(len(rows), dtype=np.int64)
        for c in range(rows.shape[1]):
            v = rows[:, c] - self._lo[c]
            span = int(v.max()) + 1 if len(v) else 1
            if (int(rank.max(initial=0)) + 1) * span >= 2**62:
                raise OverflowError("row index: key range too large")  # pragma: no cover
            comb = rank * span + v
            uniq = np.unique(comb)
            rank = np.searchsorted(uniq, comb)
            self._levels.append(uniq)
            self._spans.append(span)
        order = np.argsort(rank, kind="stable")
        self._rank_sorted = rank[order]
        self._row_of = order

    def find(self, q: np.ndarray) -> np.ndarray:
        q = np.asarray(q, dtype=np.int64).reshape(-1, len(self._levels))
        ok = np.ones(len(q), dtype=bool)
        rank = np.zeros(len(q), dtype=np.int64)
        for c, (uniq, span) in enumerate(zip(self._levels, self._spans, strict=True)):
            v = q[:, c] - self._lo[c]
            ok &= (v >= 0) & (v < span)
            comb = rank * span + np.where(ok, v, 0)
            pos = np.minimum(np.searchsorted(uniq, comb), len(uniq) - 1)
            ok &= uniq[pos] == comb
            rank = np.where(ok, pos, 0)
        out = np.full(len(q), -1, dtype=np.int64)
        if len(self._rank_sorted):
            pos = np.minimum(np.searchsorted(self._rank_sorted, rank), len(self._rank_sorted) - 1)
            hit = ok & (self._rank_sorted[pos] == rank)
            out[hit] = self._row_of[pos[hit]]
        return out


class _PointIndex:
    """Nodes within ``tol`` of query points (quantised keys, 8 rounding corners)."""

    def __init__(self, xyz: np.ndarray, tol: float) -> None:
        self.xyz = xyz
        self.tol = tol
        self.q = 4.0 * tol
        self.index = _RowIndex(np.rint(xyz / self.q).astype(np.int64))

    def find(self, pts: np.ndarray) -> tuple[np.ndarray, np.ndarray]:
        """``(node or -1, distance of the match)`` of every point ``(m, 3)``."""
        s = pts / self.q
        lo = np.floor(s).astype(np.int64)
        out = np.full(len(pts), -1, dtype=np.int64)
        dist = np.full(len(pts), np.inf)
        for corner in np.ndindex(2, 2, 2):
            hit = self.index.find(lo + np.array(corner, dtype=np.int64))
            ok = hit >= 0
            d = np.full(len(pts), np.inf)
            d[ok] = np.linalg.norm(self.xyz[hit[ok]] - pts[ok], axis=1)
            better = ok & (d <= self.tol) & (d < dist)
            out[better], dist[better] = hit[better], d[better]
        return out, dist


