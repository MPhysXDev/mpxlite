def _tag_sets(
    tag_map: Mapping[int, int | Iterable[int]] | None,
) -> dict[int, tuple[int, ...]]:
    out: dict[int, tuple[int, ...]] = {}
    for a, b in (tag_map or {}).items():
        out[int(a)] = (int(b),) if isinstance(b, (int, np.integer)) else tuple(
            sorted({int(v) for v in b})
        )  # fmt: skip
    return out


class _Gate:
    def __init__(self, mesh: _GateMesh, lattice: np.ndarray) -> None:
        self.mesh = mesh
        self.t = lattice
        self.tinv = np.linalg.inv(lattice)
        self.tol = MATCH_TOL * float(np.max(np.abs(lattice)))
        xyz = mesh.xyz
        self.u = xyz[:, :2] @ self.tinv
        self.lo = self.u.min(axis=0)
        self.points = _PointIndex(xyz, self.tol)
        # copies[j, s]: the node at x_j + _SHIFTS[s] (lattice), or -1
        self.copies = np.column_stack([self._at(self.u + s, xyz[:, 2])[0] for s in _SHIFTS])
        self.copies[:, 0] = np.arange(len(xyz))
        self.cls = np.where(self.copies >= 0, self.copies, len(xyz)).min(axis=1)
        self.index = [self._element_index(k) for k in mesh.kinds]

    def _at(self, u: np.ndarray, z: np.ndarray) -> tuple[np.ndarray, np.ndarray]:
        return self.points.find(np.column_stack([u @ self.t, z]))

    @staticmethod
    def _element_index(kind: _Kind) -> tuple[_RowIndex, _RowIndex]:
        srt = np.sort(kind.conn, axis=1)
        return _RowIndex(srt), _RowIndex(np.column_stack([srt, kind.phys]))

    def node_map(self, op: LatticeOp) -> tuple[np.ndarray, np.ndarray, np.ndarray]:
        """``(node j or -1, lattice shift s, residual)``: ``G x_i = x_j + s``."""
        img = op.apply(self.u)
        s0 = np.floor(img - self.lo + 1e-9).astype(np.int64)
        z = self.mesh.xyz[:, 2]
        out = np.full(len(img), -1, dtype=np.int64)
        shift = np.zeros_like(s0)
        res = np.zeros(len(img))
        todo = np.arange(len(img))
        for d in _SHIFTS:
            if not todo.size:
                break
            s = s0[todo] + d
            hit, dist = self._at(img[todo] - s, z[todo])
            ok = hit >= 0
            out[todo[ok]], shift[todo[ok]], res[todo[ok]] = hit[ok], s[ok], dist[ok]
            todo = todo[~ok]
        return out, shift, res

    def worst_mismatch(self, op: LatticeOp, bad: np.ndarray) -> float:
        """Largest distance of the images of nodes ``bad`` to the nearest node (modulo lattice)."""
        if not bad.size:
            return 0.0
        sel = bad[:: max(1, len(bad) // _MAX_PROBE)][:_MAX_PROBE]
        img = op.apply(self.u[sel])
        img -= np.floor(img - self.lo)
        p = np.column_stack([img @ self.t, self.mesh.xyz[sel, 2]])
        best = np.full(len(sel), np.inf)
        for s in _SHIFTS:
            q = self.mesh.xyz + np.r_[s @ self.t, 0.0]
            for a in range(0, len(p), 64):
                d = np.linalg.norm(p[a : a + 64, None, :] - q[None, :, :], axis=2).min(axis=1)
                best[a : a + 64] = np.minimum(best[a : a + 64], d)
        return float(best.max())

    def image_elements(
        self, kind: _Kind, index: _RowIndex, op: LatticeOp, nmap: np.ndarray, nshift: np.ndarray
    ) -> tuple[np.ndarray, np.ndarray]:
        """``(nodes_ok, image rows)``: rows of the image element (node order kept) or ``-1``.

        The image is translated by the lattice vector ``D`` that brings its
        centroid into the window (then by the neighbours of ``D``); its node
        ``k`` is the copy of ``nmap[k]`` shifted by ``nshift[k] - D``.
        """
        conn = kind.conn
        nodes_ok = np.all(nmap[conn] >= 0, axis=1)
        d0 = np.floor(op.apply(self.u[conn]).mean(axis=1) - self.lo + 1e-9).astype(np.int64)
        img = np.full(conn.shape, -1, dtype=np.int64)
        todo = np.flatnonzero(nodes_ok)
        for dd in _SHIFTS:
            if not todo.size:
                break
            v = nshift[conn[todo]] - (d0[todo] + dd)[:, None, :]  # (t, k, 2)
            col = _shift_column(v)
            src = self.copies[np.maximum(nmap[conn[todo]], 0), np.maximum(col, 0)]
            cand = np.where(np.all(np.abs(v) <= 1, axis=2) & (col >= 0), src, -1)
            full = np.all(cand >= 0, axis=1)
            hit = np.full(len(todo), -1, dtype=np.int64)
            if full.any():
                hit[full] = index.find(np.sort(cand[full], axis=1))
            ok = hit >= 0
            img[todo[ok]] = cand[ok]
            todo = todo[~ok]
        return nodes_ok, img

    @staticmethod
    def check_tags(
        kind: _Kind,
        indexes: tuple[_RowIndex, _RowIndex],
        rows: np.ndarray,
        img: np.ndarray,
        tags: dict[int, tuple[int, ...]],
    ) -> tuple[list[tuple[int, int, tuple[int, ...], tuple[int, ...]]], set, str]:
        """Tag errors, moved tags and an example of the found elements ``rows``.

        The image of ``(nodes, a)`` must carry a declared image of ``a``
        (``a`` itself when undeclared).
        """
        idx_nodes, idx_full = indexes
        srt = np.sort(img, axis=1)
        phys = kind.phys[rows]
        errors, moved, example = [], set(), ""
        for a in np.unique(phys).tolist():
            sel = np.flatnonzero(phys == a)
            want = tags.get(a, (a,))
            hit_any = np.zeros(len(sel), dtype=bool)
            for b in want:
                hit = idx_full.find(np.column_stack([srt[sel], np.full(len(sel), b)])) >= 0
                hit_any |= hit
                if b != a and hit.any():
                    moved.add((kind.dim, int(a), int(b)))
            if hit_any.all():
                continue
            got = idx_nodes.find(srt[sel[~hit_any]])
            found = tuple(sorted(set(kind.phys[got[got >= 0]].tolist())))
            errors.append((kind.dim, int(a), want, found))
            if not example:
                k = rows[sel[np.flatnonzero(~hit_any)[0]]]
                example = (
                    f"element {kind.number[k]} of tag {kind.dim}:{a} maps onto tag(s) {list(found)}"
                )
        return errors, moved, example

    def check(self, op: LatticeOp, tags: dict[int, tuple[int, ...]]) -> OperationCheck:
        """The node, element, tag and node-order checks of one operation."""
        mesh = self.mesh
        nmap, nshift, nres = self.node_map(op)
        bad_nodes = np.flatnonzero(nmap < 0)
        n_el = n_unmapped = n_reordered = 0
        tag_errors: list[tuple[int, int, tuple[int, ...], tuple[int, ...]]] = []
        moved: set[tuple[int, int, int]] = set()
        examples = []
        if bad_nodes.size:
            k = int(bad_nodes[0])
            examples.append(f"node {mesh.numbers[k]} at {mesh.xyz[k].tolist()}")
        for kind, indexes in zip(mesh.kinds, self.index, strict=True):
            n_el += len(kind.conn)
            if not len(kind.conn):
                continue
            nodes_ok, img = self.image_elements(kind, indexes[0], op, nmap, nshift)
            found = np.all(img >= 0, axis=1)
            lost = np.flatnonzero(nodes_ok & ~found)
            n_unmapped += lost.size
            if lost.size:
                examples.append(f"element {kind.number[lost[0]]} (dim {kind.dim}) has no image")
            f = np.flatnonzero(found)
            num, num_img = mesh.numbers[kind.conn[f]], mesh.numbers[img[f]]
            reord = np.flatnonzero(
                np.any(np.argsort(num, axis=1) != np.argsort(num_img, axis=1), axis=1)
            )
            n_reordered += reord.size
            if reord.size:
                p = int(reord[0])
                examples.append(
                    f"element {kind.number[f[p]]} (dim {kind.dim}) nodes {num[p].tolist()} "
                    f"map to {num_img[p].tolist()} (another node order)"
                )
            errs, mv, ex = self.check_tags(kind, indexes, f, img[f], tags)
            tag_errors += errs
            moved |= mv
            examples += [ex] if ex else []
        return OperationCheck(
            op=op.name,
            n_nodes=len(nmap),
            n_nodes_unmapped=int(bad_nodes.size),
            worst_node_mismatch=self.worst_mismatch(op, bad_nodes),
            max_node_residual=float(nres[nmap >= 0].max(initial=0.0)),
            n_elements=n_el,
            n_elements_unmapped=n_unmapped,
            n_reordered=n_reordered,
            tag_errors=tuple(tag_errors),
            tag_map=tuple(sorted(moved)),
            example=examples[0] if examples else "",
        )

    def orbit_conflicts(self, group: Sequence[LatticeOp]) -> tuple[int, str]:
        """Elements with two distinct nodes of one orbit of ``group`` (and of the lattice)."""
        orb = self.cls.copy()
        for op in group:
            nmap, _, _ = self.node_map(op)
            ok = nmap >= 0
            orb[ok] = np.minimum(orb[ok], self.cls[nmap[ok]])
        n_bad, example = 0, ""
        for kind in self.mesh.kinds:
            if not len(kind.conn):
                continue
            o = np.sort(orb[kind.conn], axis=1)
            bad = np.any(o[:, 1:] == o[:, :-1], axis=1)
            n_bad += int(np.count_nonzero(bad))
            if bad.any() and not example:
                k = int(np.flatnonzero(bad)[0])
                example = (
                    f"element {kind.number[k]} (dim {kind.dim}) nodes "
                    f"{self.mesh.numbers[kind.conn[k]].tolist()}"
                )
        return n_bad, example


def _shift_column(v: np.ndarray) -> np.ndarray:
    """Column of :data:`_SHIFTS` of every integer shift ``v`` ``(..., 2)`` in ``{-1, 0, 1}^2``."""
    lut = np.full((3, 3), -1, dtype=np.int64)
    for c, (a, b) in enumerate(_SHIFTS.tolist()):
        lut[a + 1, b + 1] = c
    vv = np.clip(v, -1, 1) + 1
    return lut[vv[..., 0], vv[..., 1]]


def element_tag_map(
    element_tags: Sequence[Iterable[int]], perm: Sequence[int]
) -> dict[int, tuple[int, ...]]:
    """Declared tag images of an operation that maps element ``e`` onto element ``perm[e]``.

    Every tag of element ``e`` may map onto any tag of element ``perm[e]``
    (a ``tag_maps`` entry of :func:`check_mesh_symmetry`, for tags carried by
    elements that an operation exchanges).
    """
    tags = [sorted({int(v) for v in t}) for t in element_tags]
    if len(perm) != len(tags):
        raise ValueError(f"{len(perm)} element images for {len(tags)} elements")
    out: dict[int, set[int]] = {}
    for e, f in enumerate(perm):
        for a in tags[e]:
            out.setdefault(a, set()).update(tags[int(f)])
    return {a: tuple(sorted(b)) for a, b in out.items()}


def check_mesh_symmetry(
    msh_path: Path | str,
    lattice: object,
    operations: Sequence[LatticeOp],
    *,
    tag_maps: Mapping[str, Mapping[int, int | Iterable[int]]] | None = None,
) -> MeshSymmetryReport:
    """Check a mesh against declared operations (module doc); never raises on a failure.

    Args:
        msh_path: The mesh (MSH 2.x ASCII, linear tetrahedra / triangles).
        lattice: Rows ``T_1``, ``T_2`` (m) of the in-plane lattice.
        operations: The declared operations (any :class:`LatticeOp`: rotations,
            mirrors, glides; any lattice). The identity may be included.
        tag_maps: Per operation name, the declared image of the physical tags
            it moves (``tag -> image tag`` or a set of allowed images, e.g.
            the tags of the surface it maps onto); every other tag
            must be fixed. A tag number applies to every dimension.

    Returns:
        The :class:`MeshSymmetryReport`.

    Raises:
        UnsupportedMeshFormatError: not MSH 2.x ASCII, or another element type.
    """
    t0 = time.perf_counter()
    path = Path(msh_path).expanduser().resolve()
    t = _lattice(lattice)
    ops = list(operations)
    if not ops:
        raise ValueError("no operation to check")
    names = [o.name for o in ops]
    unknown = sorted(set(tag_maps or {}) - set(names))
    if unknown:
        raise ValueError(f"tag_maps names unknown operations {unknown} (have {names})")
    gate = _Gate(_read(path), t)
    checks = tuple(gate.check(o, _tag_sets((tag_maps or {}).get(o.name))) for o in ops)
    group = lattice_group(ops)
    n_conf, example = gate.orbit_conflicts(group[1:])
    return MeshSymmetryReport(path, checks, len(group), n_conf, example, time.perf_counter() - t0)


def require_mesh_symmetry(
    msh_path: Path | str,
    lattice: object,
    operations: Sequence[LatticeOp],
    *,
    tag_maps: Mapping[str, Mapping[int, int | Iterable[int]]] | None = None,
    what: str = "the declared symmetry",
) -> MeshSymmetryReport:
    """:func:`check_mesh_symmetry`, raising :class:`MeshSymmetryError` on any failure.

    ``what`` names the use in the message (e.g. ``"the folding of the Bloch set"``).
    """
    rep = check_mesh_symmetry(msh_path, lattice, operations, tag_maps=tag_maps)
    if not rep.ok:
        raise MeshSymmetryError(
            f"{what}: the mesh does not have the declared symmetry (node order included)\n"
            f"{rep.summary()}",
            rep,
        )
    return rep
