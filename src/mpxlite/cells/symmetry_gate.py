@dataclass(frozen=True)
class OperationCheck:
    """Outcome of the gate for one operation."""

    op: str
    n_nodes: int
    n_nodes_unmapped: int = 0
    """Nodes whose image is not a node (modulo the lattice)."""
    worst_node_mismatch: float = 0.0
    """Largest distance (m) of an unmatched node image to the nearest node (0 if none; over
    at most 256 sampled unmatched nodes)."""
    max_node_residual: float = 0.0
    """Largest distance (m) of a matched node image to its node (the round-off)."""
    n_elements: int = 0
    """Tetrahedra and triangles checked (Bloch-surface triangles excluded)."""
    n_elements_unmapped: int = 0
    """Elements whose image (nodes all matched) is not an element."""
    n_reordered: int = 0
    """Elements whose image has another node-number order (basis not invariant)."""
    tag_errors: tuple[tuple[int, int, tuple[int, ...], tuple[int, ...]], ...] = ()
    """``(dim, tag, expected image tags, found image tags)`` of every violated tag."""
    tag_map: tuple[tuple[int, int, int], ...] = ()
    """``(dim, tag, image tag)`` of every physical tag that the operation moves."""
    example: str = ""
    """One failing element / node (diagnostics)."""

    @property
    def ok(self) -> bool:
        """Nodes, elements, tags and node order all invariant."""
        return not (
            self.n_nodes_unmapped or self.n_elements_unmapped or self.n_reordered or self.tag_errors
        )

    def summary(self) -> str:
        """One line."""
        parts = [f"{self.op}: {self.n_nodes} nodes, {self.n_elements} elements"]
        if self.n_nodes_unmapped:
            parts.append(
                f"{self.n_nodes_unmapped} node images are not nodes "
                f"(worst mismatch {self.worst_node_mismatch:.3e} m)"
            )
        if self.n_elements_unmapped:
            parts.append(f"{self.n_elements_unmapped} element images are not elements")
        if self.n_reordered:
            parts.append(f"{self.n_reordered} elements with another node order")
        for d, a, want, got in self.tag_errors[:4]:
            parts.append(f"tag {d}:{a} maps to {list(got)}, declared {list(want)}")
        if self.ok:
            moved = ", ".join(f"{d}:{a}->{b}" for d, a, b in self.tag_map) or "none"
            parts.append(f"ok (residual {self.max_node_residual:.1e} m, moved tags {moved})")
        elif self.example:
            parts.append(f"e.g. {self.example}")
        return "; ".join(parts)


@dataclass(frozen=True)
class MeshSymmetryReport:
    """Outcome of :func:`check_mesh_symmetry`."""

    path: Path
    operations: tuple[OperationCheck, ...]
    group_order: int
    """Order of the group generated by the operations (modulo the lattice)."""
    n_orbit_conflicts: int = 0
    """Elements holding two distinct nodes of one orbit of the group."""
    orbit_example: str = ""
    elapsed_s: float = 0.0

    @property
    def ok(self) -> bool:
        """Every operation passes and no element holds two nodes of one orbit."""
        return self.n_orbit_conflicts == 0 and all(o.ok for o in self.operations)

    @property
    def failing(self) -> tuple[OperationCheck, ...]:
        """The operations that fail."""
        return tuple(o for o in self.operations if not o.ok)

    def summary(self) -> str:
        """Multi-line summary (one line per failing operation)."""
        head = (
            f"{self.path.name}: {len(self.operations)} operations (group of order "
            f"{self.group_order}), {'ok' if self.ok else 'FAILED'} in {self.elapsed_s:.2f} s"
        )
        lines = [head]
        if self.n_orbit_conflicts:
            lines.append(
                f"  {self.n_orbit_conflicts} elements hold two nodes of one orbit of the group "
                f"(no numbering can preserve their order; the rotation axes / mirror planes must "
                f"be made of mesh edges / faces, e.g. a mesh replicated from a fundamental "
                f"domain); e.g. {self.orbit_example}"
            )
        lines += [f"  {o.summary()}" for o in (self.failing if not self.ok else self.operations)]
        return "\n".join(lines)


